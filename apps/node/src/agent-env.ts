/* A tmux server may outlive the node and still hold old settings. Reset them before reading Hornhoof's private env file. */
export const RESET_AGENT_ENV = `unset ${[...NODE_ONLY].join(' ')}`;

export function agentEnv(inherited: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  return Object.fromEntries(Object.entries(inherited).filter(([key]) => !NODE_ONLY.has(key) && !key.startsWith('HORNHOOF_')));
}
