/* Stage 3 pack-agnostic synthetic 5-year company simulator (150 agents, 160000 accepted tasks,
   30 major goals) inside a 150x150 procedural map generated by any WorldPackManifest's terrainRecipe.
   Works identically on open-surface worlds and subterranean excavatable worlds (carving halls
   and corridors out of bedrock). Records monthly snapshots and exact tile-area breakdowns
   for Year 1, Year 2 and Year 5. Contains zero theme-specific words, files or colours. */

import {
  bindCityMap,
  computeCityTileBreakdown,
  createCity,
  densifyCity,
  growBuildingForProgress,
  placeBuilding,
  rebuildWallIfNeeded,
  recordTrafficRoute,
  refreshCityMetrics,
  serializeCityLayout,
  type CityLayoutSnapshot,
  type CityState,
  type CityTileBreakdown,
} from './city-layout';
import type { WorldPackManifest } from './manifest';
import { generateWorldTerrain, type GeneratedWorldMap } from './terrain-engine';

export const SIM_SEEDS = ['hornhoof', 'velvet-ops', 'meridian-hq'] as const;
export const SIM_KNOBS = [0.0, 0.5, 1.0] as const;

export const FIVE_YEAR_TARGETS = {
  months: 60,
  agents: 150,
  acceptedTasks: 160_000,
  majorGoals: 30,
  departments: 10,
  machines: 6,
  subscriptions: 15,
  tasksPerStatue: 2_000,
} as const;

export type SimFrame = Readonly<{
  month: number;
  year: number;
  agents: number;
  acceptedTasks: number;
  majorGoals: number;
  statues: number;
  buildingsCount: number;
  wallGeneration: number;
  densifiedUpgrades: number;
  mergedBuildings: number;
  excavatedTiles: number;
  breakdown: CityTileBreakdown;
  snapshot: CityLayoutSnapshot;
}>;

export type FiveYearSimOptions = Readonly<{
  seed: string;
  mapSize?: number;
  orderChaos: number;
  recordSnapshots?: boolean;
}>;

export type FiveYearSimResult = Readonly<{
  packId: string;
  seed: string;
  orderChaos: number;
  map: GeneratedWorldMap;
  city: CityState;
  frames: readonly SimFrame[];
  year1Breakdown: CityTileBreakdown;
  year2Breakdown: CityTileBreakdown;
  year5Breakdown: CityTileBreakdown;
  totalAgents: number;
  totalAcceptedTasks: number;
  totalMajorGoals: number;
  coordinateJumps: number;
}>;

/* Canonical agent level threshold from accepted tasks: round(2 * (L - 1)^1.8), levels 1..30. */
export function agentLevelFromTasks(acceptedTasks: number): number {
  let level = 1;
  for (let l = 2; l <= 30; l++) {
    const threshold = Math.round(2 * Math.pow(l - 1, 1.8));
    if (acceptedTasks >= threshold) level = l;
    else break;
  }
  return level;
}

/* Distributes 160000 tasks across 60 months along a realistic growing company curve (exact sum = 160000). */
function monthlyTaskSchedule(months: number, total: number): number[] {
  const weights: number[] = [];
  let sumW = 0;
  for (let m = 1; m <= months; m++) {
    const w = 0.25 + 1.55 * (m / months);
    weights.push(w);
    sumW += w;
  }
  const out = weights.map(w => Math.floor((w / sumW) * total));
  let diff = total - out.reduce((a, b) => a + b, 0);
  let idx = months - 1;
  while (diff > 0) {
    out[idx] = (out[idx] ?? 0) + 1;
    diff--;
    idx = idx > 0 ? idx - 1 : months - 1;
  }
  return out;
}

/* Runs the full 5-year (60-month) synthetic company growth simulation inside a 150x150 pack map. */
export function runFiveYearSimulation(
  pack: WorldPackManifest,
  options: FiveYearSimOptions,
): FiveYearSimResult {
  const mapSize = options.mapSize ?? pack.mapSize;
  const map = generateWorldTerrain(pack, { seed: options.seed, mapSize });
  const city = bindCityMap(createCity(map, { orderChaos: options.orderChaos }), map);
  const recordSnapshots = options.recordSnapshots ?? true;

  const taskSchedule = monthlyTaskSchedule(FIVE_YEAR_TARGETS.months, FIVE_YEAR_TARGETS.acceptedTasks);
  const deptTasks = new Map<string, number>();
  const deptStatuesBuilt = new Map<string, number>();
  const agentTasks = new Map<string, number>();

  let agentsCount = 0;
  let tasksCount = 0;
  let goalsCount = 0;
  let deptsCount = 0;
  let hubsCount = 0;
  let suppliesCount = 0;
  let coordinateJumps = 0;

  const prevCoords = new Map<string, { col: number; row: number }>();
  const frames: SimFrame[] = [];
  let year1Breakdown: CityTileBreakdown | null = null;
  let year2Breakdown: CityTileBreakdown | null = null;
  let year5Breakdown: CityTileBreakdown | null = null;

  const checkStability = () => {
    for (const b of city.buildings) {
      const prev = prevCoords.get(b.id);
      if (prev && (prev.col !== b.col || prev.row !== b.row)) {
        coordinateJumps++;
      }
      prevCoords.set(b.id, { col: b.col, row: b.row });
    }
  };

  const addDepartment = (idx: number) => {
    const id = `dept-${idx}`;
    placeBuilding(city, { id, kind: 'department', departmentId: id, label: `Department ${idx}` }, map);
    deptTasks.set(id, 0);
    deptStatuesBuilt.set(id, 0);
  };

  const addHub = (idx: number) => {
    const id = `machine-${idx}`;
    placeBuilding(city, { id, kind: 'district_hub', districtId: id, label: `Machine ${idx}` }, map);
    /* Each district also receives one day-laborer lodge on its outer edge for one-shot calls. */
    placeBuilding(
      city,
      { id: `flophouse-${idx}`, kind: 'flophouse', districtId: id, label: `Lodge ${idx}` },
      map,
    );
  };

  const addSupply = (idx: number) => {
    placeBuilding(city, { id: `supply-${idx}`, kind: 'supply', label: `Supply ${idx}` }, map);
  };

  const addGoal = (idx: number) => {
    const placed = placeBuilding(city, { id: `goal-${idx}`, kind: 'monument', label: `Goal ${idx}` }, map);
    if (!placed) {
      /* Under extreme space pressure, densify an existing monument complex in place. */
      const existing = city.buildings.find(b => b.kind === 'monument');
      if (existing) {
        existing.goalCount++;
        existing.floors = Math.min(5, existing.floors + 1);
        city.metrics.densifiedUpgrades++;
      }
    }
  };

  const addAgent = (idx: number) => {
    const agentId = `agent-${idx}`;
    const districtId = `machine-${((idx - 1) % Math.max(1, hubsCount)) + 1}`;
    const departmentId = `dept-${((idx - 1) % Math.max(1, deptsCount)) + 1}`;
    const placed = placeBuilding(
      city,
      {
        id: `house-${idx}`,
        kind: 'house',
        label: `Resident ${idx}`,
        districtId,
        departmentId,
        residentIds: [agentId],
      },
      map,
    );
    if (!placed) {
      const target =
        city.buildings.find(b => b.kind === 'house' && b.districtId === districtId && b.residentIds.length < 4) ??
        city.buildings.find(b => b.kind === 'house');
      if (target) {
        target.residentIds.push(agentId);
        target.floors = Math.min(4, target.floors + 1);
        city.metrics.densifiedUpgrades++;
      }
    }
    agentTasks.set(agentId, 0);
  };

  for (let month = 1; month <= FIVE_YEAR_TARGETS.months; month++) {
    /* Scale machines (2 -> 6), departments (4 -> 10), subscriptions (3 -> 15). */
    const targetHubs = Math.min(FIVE_YEAR_TARGETS.machines, 2 + Math.floor((month - 1) / 11));
    while (hubsCount < targetHubs) addHub(++hubsCount);

    const targetDepts = Math.min(FIVE_YEAR_TARGETS.departments, 4 + Math.floor((month - 1) / 9));
    while (deptsCount < targetDepts) addDepartment(++deptsCount);

    const targetSupplies = Math.min(FIVE_YEAR_TARGETS.subscriptions, 3 + Math.floor((month - 1) / 4.5));
    while (suppliesCount < targetSupplies) addSupply(++suppliesCount);

    /* Scale agents smoothly from 12 in month 1 up to exact 150 in month 60. */
    const targetAgents =
      month === FIVE_YEAR_TARGETS.months
        ? FIVE_YEAR_TARGETS.agents
        : Math.min(FIVE_YEAR_TARGETS.agents, 10 + Math.round((month / FIVE_YEAR_TARGETS.months) * 140));
    while (agentsCount < targetAgents) addAgent(++agentsCount);

    /* Add 1 major top-level goal every 2 months (30 major goals over 5 years). */
    const targetGoals = Math.min(FIVE_YEAR_TARGETS.majorGoals, Math.ceil(month / 2));
    while (goalsCount < targetGoals) addGoal(++goalsCount);

    /* Distribute monthly accepted tasks across departments & agents. */
    const monthTasks = taskSchedule[month - 1] ?? 0;
    tasksCount += monthTasks;

    const perDept = Math.floor(monthTasks / Math.max(1, deptsCount));
    let deptRem = monthTasks - perDept * deptsCount;
    for (let d = 1; d <= deptsCount; d++) {
      const id = `dept-${d}`;
      const added = perDept + (deptRem > 0 ? 1 : 0);
      if (deptRem > 0) deptRem--;
      const totalD = (deptTasks.get(id) ?? 0) + added;
      deptTasks.set(id, totalD);

      /* Update department construction stage (1..10) and grow footprint inside its 5x5 reserved lot. */
      const deptB = city.buildings.find(b => b.id === id);
      if (deptB) {
        deptB.stage = Math.min(deptB.maxStage, 1 + Math.floor(totalD / 1600));
        growBuildingForProgress(city, map, deptB);
      }

      /* Spawn one statue along the department's street every 2000 department tasks (growing 1x1 -> 2x2 -> 3x3). */
      const targetStatues = Math.floor(totalD / FIVE_YEAR_TARGETS.tasksPerStatue);
      let built = deptStatuesBuilt.get(id) ?? 0;
      while (built < targetStatues) {
        built++;
        placeBuilding(
          city,
          { id: `statue-${id}-${built}`, kind: 'statue', departmentId: id, stage: 20, label: `Statue ${id} #${built}` },
          map,
        );
        deptStatuesBuilt.set(id, built);
      }
    }

    /* Update ruler residence stage (1..5) from company-wide tasks and grow 2x2 -> 6x6 inside royal lot. */
    const residence = city.buildings[0];
    if (residence) {
      residence.stage = Math.min(residence.maxStage, 1 + Math.floor(tasksCount / 28_000));
      residence.level = Math.min(30, 1 + Math.floor(tasksCount / 5_500));
      growBuildingForProgress(city, map, residence);
    }

    /* Advance district hubs & day-laborer lodges with company tenure. */
    for (const b of city.buildings) {
      if (b.kind === 'district_hub') {
        b.stage = Math.min(b.maxStage, 1 + Math.floor(month / 12));
        growBuildingForProgress(city, map, b);
      } else if (b.kind === 'flophouse') {
        b.stage = Math.min(b.maxStage, 1 + Math.floor(month / 15));
        growBuildingForProgress(city, map, b);
      }
    }

    /* Update agent house levels from accepted tasks and grow each home (1x1 -> 2x2 -> 3x3 -> 4x4) in place. */
    const avgPerAgent = Math.max(1, Math.floor(monthTasks / Math.max(1, agentsCount)));
    for (const b of city.buildings) {
      if (b.kind !== 'house') continue;
      let maxLvl = b.level;
      for (const rid of b.residentIds) {
        const nextTasks = (agentTasks.get(rid) ?? 0) + avgPerAgent;
        agentTasks.set(rid, nextTasks);
        const lvl = agentLevelFromTasks(nextTasks);
        if (lvl > maxLvl) maxLvl = lvl;
      }
      b.level = maxLvl;
      b.stage = Math.min(b.maxStage, Math.max(1, Math.ceil(maxLvl / 3)));
      growBuildingForProgress(city, map, b);
    }

    /* Sample realistic street traffic routes (houses -> departments -> residence/monuments/supplies). */
    const depts = city.buildings.filter(b => b.kind === 'department');
    const houses = city.buildings.filter(b => b.kind === 'house');
    const supplies = city.buildings.filter(b => b.kind === 'supply');
    const monuments = city.buildings.filter(b => b.kind === 'monument');
    const trafficWeight = Math.max(2, Math.round(monthTasks / 450));
    if (residence && depts.length > 0) {
      const dept = depts[month % depts.length]!;
      recordTrafficRoute(city, dept.door, residence.door, trafficWeight);
      if (houses.length > 0) {
        const house = houses[(month * 7) % houses.length]!;
        recordTrafficRoute(city, house.door, dept.door, Math.max(1, Math.round(trafficWeight * 0.7)));
      }
      if (supplies.length > 0) {
        const supply = supplies[month % supplies.length]!;
        recordTrafficRoute(city, supply.door, residence.door, Math.max(1, Math.round(trafficWeight * 0.5)));
      }
      if (monuments.length > 0) {
        const mon = monuments[month % monuments.length]!;
        recordTrafficRoute(city, dept.door, mon.door, Math.max(1, Math.round(trafficWeight * 0.8)));
      }
    }

    /* Expand the single outer city wall when outgrown, converting old wall rings to ring streets. */
    if (month === 2 || month % 3 === 0 || month === FIVE_YEAR_TARGETS.months) {
      rebuildWallIfNeeded(city, map, month === FIVE_YEAR_TARGETS.months);
    }

    /* Trigger urban densification (in-place lot/floor upgrades + merging small neighbor houses) in Years 2..5. */
    if (month >= 18 && month % 4 === 0) {
      densifyCity(city, map, { maxUpgrades: 3, maxMerges: month >= 24 ? 1 : 0 });
    }

    refreshCityMetrics(city);
    checkStability();

    const needBreakdown = recordSnapshots || month === 12 || month === 24 || month === FIVE_YEAR_TARGETS.months;
    const breakdown = needBreakdown ? computeCityTileBreakdown(city, map) : null;
    if (month === 12 && breakdown) year1Breakdown = breakdown;
    if (month === 24 && breakdown) year2Breakdown = breakdown;
    if (month === FIVE_YEAR_TARGETS.months && breakdown) year5Breakdown = breakdown;

    if (recordSnapshots && breakdown) {
      frames.push({
        month,
        year: Math.ceil(month / 12),
        agents: agentsCount,
        acceptedTasks: tasksCount,
        majorGoals: goalsCount,
        statues: city.buildings.filter(b => b.kind === 'statue').length,
        buildingsCount: city.buildings.length,
        wallGeneration: city.wallGeneration,
        densifiedUpgrades: city.metrics.densifiedUpgrades,
        mergedBuildings: city.metrics.mergedBuildings,
        excavatedTiles: city.excavatedTiles.size,
        breakdown,
        snapshot: serializeCityLayout(city),
      });
    }
  }

  const finalBreakdown = year5Breakdown ?? computeCityTileBreakdown(city, map);
  return {
    packId: pack.id,
    seed: options.seed,
    orderChaos: options.orderChaos,
    map,
    city,
    frames,
    year1Breakdown: year1Breakdown ?? finalBreakdown,
    year2Breakdown: year2Breakdown ?? finalBreakdown,
    year5Breakdown: finalBreakdown,
    totalAgents: agentsCount,
    totalAcceptedTasks: tasksCount,
    totalMajorGoals: goalsCount,
    coordinateJumps,
  };
}
