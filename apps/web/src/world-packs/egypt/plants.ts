/* Ancient Egypt plants, wind and light: pack-owned data for the engine's generic plant layer.
   Placement follows the river valley: dense reeds and papyrus right at the waterline, date palms in groups of three to
   seven along the green strip, green bushes and tufts in the grass, dry grass, thorn, dry bushes and pebbles spread
   evenly over the sand, a few acacias in the open desert and fig trees at the oases. Every plant is painted art from
   the art folder; the procedural silhouettes stand in only while it is missing. */

import type { LightingSpec, PlantArtSpec, PlantKindSpec, WindSpec } from '../../world/manifest';

/* Ground the plants must stay off: bare rock and quarry stone. */
const NO_STONE = { rock: 0.12, quarry: 0.08 } as const;

/* Painted variants in the art folder (veg/<name>.png, its wind weights veg/<name>_w.png and passport veg/<name>.json). */
function veg(...names: string[]): PlantArtSpec[] {
  return names.map(n => ({ image: `veg/${n}.png`, windMask: `veg/${n}_w.png`, passport: `veg/${n}.json` }));
}

/* Small flat ground details (decals/<name>.png): no wind, no passport, anchored at their middle. */
function decals(...names: string[]): PlantArtSpec[] {
  return names.map(n => ({ image: `decals/${n}.png` }));
}

