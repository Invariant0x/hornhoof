export function attachRunningAgents(
  machines: MachineView[],
  byMachine: Map<string, RunningAgent[]>,
): MachineView[] {
  return machines.map(m => ({
    ...m,
    running: {
      ...m.running,
      agents: byMachine.get(m.id) ?? [],
    },
  }));
}
