#!/bin/sh
# Installs the Hornhoof relay on the edge droplet: frps, the relay API, their users and services.
# Run as root from the folder that holds the files next to it. Safe to run again: frps restarts (and every tunnel
# reconnects) only when its binary or config changed.
set -eu
cd "$(dirname "$0")"
FRP_VERSION=0.71.1
FRP_SHA256=1d9875210972a5d1a62b2dc4c48df45ab0af05d3ca1b5e494a014428259df803
restart_frps=''

if [ "$(/usr/local/bin/frps -v 2> /dev/null || true)" != "$FRP_VERSION" ]; then
  tmp=$(mktemp -d)
  curl -fsSL -o "$tmp/frp.tgz" "https://github.com/fatedier/frp/releases/download/v$FRP_VERSION/frp_${FRP_VERSION}_linux_amd64.tar.gz"
  echo "$FRP_SHA256  $tmp/frp.tgz" | sha256sum -c - > /dev/null
  tar -xzf "$tmp/frp.tgz" -C "$tmp"
  install -m 755 "$tmp/frp_${FRP_VERSION}_linux_amd64/frps" /usr/local/bin/frps
  rm -rf "$tmp"
  restart_frps=1
fi

id frps > /dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin frps
id hornhoof-relay > /dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin hornhoof-relay

install -d -m 755 /usr/local/lib/hornhoof-relay
install -m 755 relay.py /usr/local/lib/hornhoof-relay/relay.py
install -m 755 hornhoof-relay /usr/local/sbin/hornhoof-relay

install -d -m 750 -o root -g frps /etc/frp
install -m 644 404.html /etc/frp/404.html
pass=$(sed -n 's/^webServer.password = "\([0-9a-f]*\)"$/\1/p' /etc/frp/frps.toml 2> /dev/null || true)
[ -n "$pass" ] || pass=$(openssl rand -hex 16)
sed "s/@WEB_PASSWORD@/$pass/" frps.toml > /etc/frp/frps.toml.new
if ! cmp -s /etc/frp/frps.toml.new /etc/frp/frps.toml; then restart_frps=1; fi
install -m 640 -o root -g frps /etc/frp/frps.toml.new /etc/frp/frps.toml
rm -f /etc/frp/frps.toml.new

[ -f /etc/caddy/blocked.caddy ] || echo '# Generated by hornhoof-relay from blocked bindings. Do not edit.' > /etc/caddy/blocked.caddy

for unit in hornhoof-relay.service frps.service; do
  if ! cmp -s "$unit" "/etc/systemd/system/$unit"; then
    install -m 644 "$unit" "/etc/systemd/system/$unit"
    [ "$unit" = frps.service ] && restart_frps=1
  fi
done
systemctl daemon-reload
systemctl enable hornhoof-relay frps > /dev/null 2>&1
systemctl restart hornhoof-relay
if [ -n "$restart_frps" ] || ! systemctl is-active -q frps; then systemctl restart frps; fi
echo "relay setup done"
