import { execFileSync } from 'node:child_process';
import { fileURLToPath, URL } from 'node:url';
import { resolve } from 'node:path';

const PARTS = ['apps/server', 'apps/web', 'apps/node', 'packages/protocol'];

/* All tracked files under src, including styles, declarations and fonts. This is a file inventory, not an import graph. */
export function inventoryOf(files) {
  return PARTS.map(part => {
    const modules = new Map();
    const sources = files.filter(file => file.startsWith(`${part}/src/`));
    for (const file of sources) {
      const path = file.slice(`${part}/src/`.length).split('/');
      const module = part === 'apps/server' && path[0] === 'modules' ? path.slice(0, 2).join('/') : path[0];
      modules.set(module, (modules.get(module) ?? 0) + 1);
    }
    return { part, files: sources.length, modules: [...modules].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0) };
  });
}

export function renderInventory({ commit, version, files }) {
  const lines = [
    '# Release source inventory', '',
    `Release **${version}**, commit \`${commit}\`. This snapshot describes that release, not the moving development branch.`, '',
    'Generated by `scripts/module-inventory.mjs` from the Git tree, without reading the worktree or running services.',
    'Every tracked file under each package\'s `src/` counts once, including declarations, styles, fonts and other assets.',
    'Server domains are the folders under `src/modules/`; other groups are direct children of `src/`.',
    'Tests, migrations, generated builds, the updater and install scripts are outside these counts.',
    'These are file counts, not executable line counts or dependency measurements. No import-cycle count is inferred from them.', '',
    '## Reproduce', '', 'From the repository root, with Node and Git available:', '', '```sh',
    `node scripts/module-inventory.mjs ${commit}`, '```', '',
    'The command prints this Markdown. Pass another release tag or commit to inspect its inventory.',
    'A missing revision fails the command; it never substitutes the current checkout.', '',
    '## Package entry points', '',
    '- `apps/server/src/main.ts`, `front.ts`, `keeper.ts`, `app.ts`: server processes and application composition.',
    '- `apps/web/src/main.tsx`: browser application; screens and UI live under `screens/` and `ui/`.',
    '- `apps/node/src/main.ts`: machine node; providers, terminal and test execution live beside it.',
    '- `packages/protocol/src/index.ts` and its package exports: shared wire contracts and validators.', '',
  ];
  for (const { part, files: count, modules } of inventoryOf(files)) {
    lines.push(`## ${part}`, '', `${count} tracked source files. Paths below are relative to \`${part}/src/\`.`, '', '| Module or file | Files |', '| --- | ---: |');
    for (const [module, count] of modules) lines.push(`| \`${module}\` | ${count} |`);
    lines.push('');
  }
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  const commit = git(['rev-parse', '--verify', '--end-of-options', `${process.argv[2] ?? 'HEAD'}^{commit}`]);
  const { version } = JSON.parse(git(['show', `${commit}:package.json`]));
  const files = git(['ls-tree', '-r', '--name-only', '-z', commit, '--', ...PARTS.map(part => `${part}/src`)]).split('\0').filter(Boolean);
  process.stdout.write(renderInventory({ commit, version, files }));
}
